// Generates supabase/migrations/0004_lookup.sql from the parser tables in src/lib/normalize.ts,
// so the database's name parsing stays identical to the app's. Re-run after changing those tables:
//   npm run gen:lookup
import fs from 'fs'
import { BRANDS, GENERATION, HINTS, LINES, NOISE, PREFIXES } from '../src/lib/normalize'

/** JS regex source → Postgres ARE (word boundary \b is \y there; \b would mean backspace). */
const are = (re: RegExp) => re.source.replace(/\\b/g, '\\y')
const lit = (s: string) => `'${s.replace(/'/g, "''")}'`
const rows = (list: [string, RegExp][]) => list.map(([k, re], i) => `(${i}, ${lit(k)}, ${lit(are(re))})`).join(',\n    ')
const arr = (list: string[]) => `array[${list.map(lit).join(', ')}]`

const sql = `-- ModelMaster · 0004 lookup: find a device from an imperfect name, callable with the public key.
-- GENERATED by scripts/gen-lookup-sql.ts from src/lib/normalize.ts — edit those, then regenerate.
-- Safe to re-run.

create extension if not exists pg_trgm with schema extensions;
create index if not exists idx_aliases_trgm on model_aliases using gin (alias_normalized extensions.gin_trgm_ops);

-- The app's parser tables.
create or replace function mm_brand(p_upper text) returns text
language sql immutable set search_path = public as $$
  select b.mfr from (values
    ${rows(BRANDS)}
  ) as b(ord, mfr, re) where p_upper ~ b.re order by b.ord limit 1
$$;

create or replace function mm_hint(p_upper text) returns text
language sql immutable set search_path = public as $$
  select b.mfr from (values
    ${rows(HINTS)}
  ) as b(ord, mfr, re) where p_upper ~ b.re order by b.ord limit 1
$$;

create or replace function mm_line(p_upper text) returns text
language sql immutable set search_path = public as $$
  select b.line from (values
    ${rows(LINES)}
  ) as b(ord, line, re) where p_upper ~ b.re order by b.ord limit 1
$$;

create or replace function mm_norm(p text) returns text
language sql immutable as $$ select upper(regexp_replace(coalesce(p, ''), '[^A-Za-z0-9]', '', 'g')) $$;

-- Port of parse()/parseName() in normalize.ts: manufacturer, base model number, variant, line, generation.
create or replace function mm_parse(p_name text, p_mfr text default null)
returns table (mfr text, base text, variant text, line text, gen text, has_core boolean)
language plpgsql immutable set search_path = public as $$
#variable_conflict use_column
declare
  up       text := upper(coalesce(p_name, ''));
  noise    text[] := ${arr([...NOISE])};
  prefixes text[] := ${arr(PREFIXES)};
  all_t    text[];
  toks     text[] := '{}';
  t        text;
  idx      int := 0;
  core     text;
  stripped text;
  prev     text;
  nxt      text;
  p        text;
  rest     text;
  m        text[];
begin
  mfr := mm_brand(up);
  if mfr is null and p_mfr is not null and p_mfr <> '' then mfr := coalesce(mm_brand(upper(p_mfr)), p_mfr); end if;
  if mfr is null then mfr := mm_hint(up); end if;
  line := mm_line(up);
  gen := null;

  -- tokenize(): drop trademark marks and parentheticals, split on separators.
  all_t := regexp_split_to_array(regexp_replace(regexp_replace(up, '[™®©]', ' ', 'g'), '\\([^)]*\\)', ' ', 'g'), '[\\s\\-_/,.+]+');
  foreach t in array all_t loop
    continue when t = '' or t ~ '^V\\d+$';
    if t ~ '${are(GENERATION)}' then gen := coalesce(gen, t); continue; end if;
    toks := toks || t;
  end loop;

  -- First token with a digit AND a letter that is not a noise word; else first token with a digit.
  for i in 1 .. coalesce(array_length(toks, 1), 0) loop
    if toks[i] ~ '\\d' and toks[i] ~ '[A-Z]' and not toks[i] = any(noise) then idx := i; exit; end if;
  end loop;
  if idx = 0 then
    for i in 1 .. coalesce(array_length(toks, 1), 0) loop
      if toks[i] ~ '\\d' then idx := i; exit; end if;
    end loop;
  end if;
  if idx = 0 then
    base := mm_norm(p_name); variant := ''; line := null; gen := null; has_core := false;
    return next; return;
  end if;

  -- stripPrefix(): "IMC3510" → "C3510", "IR3235" → "3235".
  stripped := toks[idx];
  foreach p in array prefixes loop
    if length(stripped) > length(p) and left(stripped, length(p)) = p then
      rest := substr(stripped, length(p) + 1);
      if rest ~ '\\d' and rest ~ '^[A-Z0-9]' then stripped := rest; exit; end if;
    end if;
  end loop;
  core := stripped;

  -- A numeric-leading core keeps a short non-prefix letter token before it ("TM-255" → TM255).
  if core ~ '^\\d' and stripped = toks[idx] and idx > 1 then
    prev := toks[idx - 1];
    if prev !~ '\\d' and length(prev) <= 3 and not prev = any(noise) and not prev = any(prefixes) and mm_brand(prev) is null then
      core := prev || core;
    end if;
  end if;

  m := regexp_match(core, '^([A-Z]*\\d+)([A-Z0-9]*)$');
  if m is not null then base := m[1]; variant := m[2]; else base := core; variant := ''; end if;
  -- Canon iPF / Ricoh "PRO-NNNN" keep PRO in the model name.
  if base ~ '^\\d' and idx > 1 and toks[idx - 1] = 'PRO' then base := 'PRO-' || base; end if;
  -- A short letters-only token right after the core ("M428 FDW") is part of the variant.
  nxt := toks[idx + 1];
  if nxt is not null and nxt !~ '\\d' and length(nxt) <= 4 and not nxt = any(noise) then variant := variant || nxt; end if;
  has_core := true;
  return next;
end
$$;

-- Ranked candidates for a messy name. method: 'alias' (exact known name), 'model-number'
-- (manufacturer + model number + line/generation agree), 'similar' (fuzzy text, verify).
create or replace function lookup_model(p_name text, p_mfr text default null, p_limit int default 5)
returns table (canonical_key text, model_id uuid, manufacturer text, model text, line text, generation text,
               variant text, confidence numeric, method text)
language plpgsql stable security definer set search_path = public, extensions as $$
#variable_conflict use_column
declare
  q  record;
  nm text := mm_norm(p_name);
begin
  if nm = '' then return; end if;
  select * into q from mm_parse(p_name, p_mfr);

  -- 1. A name we have already seen and linked.
  return query
    select m.canonical_key, m.id, mf.name, m.model, m.line, m.generation, coalesce(v.variant, nullif(q.variant, '')),
           1.0::numeric, 'alias'::text
    from model_aliases a
    join models m on m.id = a.model_id
    left join manufacturers mf on mf.id = m.manufacturer_id
    left join model_variants v on v.id = a.variant_id
    where a.status = 'linked' and a.alias_normalized = nm
    group by m.id, mf.name, v.variant
    order by count(*) desc
    limit 1;
  if found then return; end if;

  -- 2. Same identity: model number, manufacturer, product line, generation.
  if q.has_core then
    return query
      select c.canonical_key, c.id, c.mfr, c.model, c.line, c.generation, nullif(q.variant, ''),
             round(least(0.95, c.raw + case when q.mfr is null and c.n = 1 then 0.1 else 0 end)::numeric, 2), 'model-number'::text
      from (
        select m.canonical_key, m.id, mf.name as mfr, m.model, m.line, m.generation, count(*) over () as n,
               0.7
                 + case when q.mfr is null then -0.1 else 0.1 end   -- brand named in the text
                 + case when q.line is not null and m.line = q.line then 0.1 else 0 end
                 + case when coalesce(q.gen, '') = coalesce(m.generation, '') then 0.05 else -0.25 end as raw
        from models m
        left join manufacturers mf on mf.id = m.manufacturer_id
        where upper(m.model) = q.base
          and (q.mfr is null or mf.name = q.mfr)
          and (q.line is null or m.line is null or m.line = q.line)
      ) c
      order by 8 desc, c.canonical_key
      limit p_limit;
    if found then return; end if;
  end if;

  -- 3. Fuzzy: closest known names (trigram similarity), best per model.
  return query
    select s.canonical_key, s.id, s.mfr, s.model, s.line, s.generation, nullif(q.variant, ''), s.score, 'similar'::text
    from (
      select distinct on (m.id) m.canonical_key, m.id, mf.name as mfr, m.model, m.line, m.generation,
             round((similarity(a.alias_normalized, nm) * 0.8)::numeric, 2) as score
      from model_aliases a
      join models m on m.id = a.model_id
      left join manufacturers mf on mf.id = m.manufacturer_id
      where a.status = 'linked' and a.alias_normalized % nm
        and (q.mfr is null or mf.name = q.mfr)
      order by m.id, similarity(a.alias_normalized, nm) desc
    ) s
    order by s.score desc
    limit p_limit;
end
$$;

-- Best single match (kept signature from 0001). Only answers when reasonably sure (confidence ≥ 0.7).
drop function if exists resolve_model(text);
create or replace function resolve_model(p_name text)
returns table (model_id uuid, canonical_key text, variant text, matches integer, confidence numeric, method text)
language sql stable security definer set search_path = public as $$
  select l.model_id, l.canonical_key, l.variant, 1, l.confidence, l.method
  from lookup_model(p_name) l
  where l.confidence >= 0.7
  order by l.confidence desc
  limit 1
$$;

-- Messy name → toners, through the same resolver.
create or replace function toners_for_name(p_name text)
returns setof model_toners
language sql stable security definer set search_path = public as $$
  select t.* from model_toners t
  where t.model_id = (select r.model_id from resolve_model(p_name) r limit 1)
$$;

-- Open the lookups to the public key (tables themselves stay authenticated-only).
grant execute on function mm_parse(text, text), lookup_model(text, text, int), resolve_model(text), toners_for_name(text) to anon, authenticated;
`
